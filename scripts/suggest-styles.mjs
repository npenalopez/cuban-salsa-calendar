// Suggests `styles` and `cubanFocused` for every festival, for review. It never touches festivals.json.
//
//   node scripts/suggest-styles.mjs [external.json]
//
// Evidence: the festival's own name and description, plus optionally an external JSON
// ({ [festivalId]: { styles: string[], category: string|null, url } }), e.g. the style lists
// published on cubansalsafestivals.com. Writes data/review/styles.md (to read) and
// data/review/styles.json (to apply with scripts/apply-styles.mjs once approved).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const { festivals } = JSON.parse(readFileSync(new URL('data/festivals.json', root), 'utf8'));
const external = process.argv[2] ? JSON.parse(readFileSync(process.argv[2], 'utf8')) : {};

const ORDER = ['casino', 'timba', 'son', 'rumba', 'afro-cuban', 'rueda', 'reggaeton', 'mixed'];

/** Words in our own text → style. */
const TEXT_RULES = [
  ['timba', /\btimba/i],
  ['casino', /\bcasino\b|salsa cubana|cuban salsa|\bcasinero/i],
  ['son', /\bson\b|son cubano|\bsonero/i],
  ['rumba', /\brumba|guaguanc|columbia|yamb[uú]/i],
  ['afro-cuban', /afro[- ]?cuban|afro[- ]?cubano|orisha|folkl?or/i],
  ['rueda', /\brueda/i],
  ['reggaeton', /reggaet|reparto/i],
  ['mixed', /bachata|kizomba|\bs?r?bk\b|\bzouk|\bon ?[12]\b|sensual|linear|\bmambo\b|\bkiz\b/i],
];
/** A name that announces other styles: "Salsa & Bachata Weekend", "SBK Congress". */
const MIXED_NAME = /bachata|kizomba|\bs?r?bk\b|sensual|\bzouk/i;
const CUBAN_TEXT = /cuba|cuban|timba|casino|rueda|afro[- ]?cuban|\bson\b/i;

/** Their style names → ours. */
const EXTERNAL_STYLES = {
  'Cuban Salsa': 'casino', Casino: 'casino', Timba: 'timba', 'Son Cubano': 'son',
  Rumba: 'rumba', 'Rumba Guaguancó': 'rumba', 'Rumba Columbia': 'rumba', 'Afro-Cuban': 'afro-cuban', Reparto: 'reggaeton',
  Bachata: 'mixed', 'Bachata Fusion': 'mixed', 'Bachata Dominicana': 'mixed', Kizomba: 'mixed',
  'Salsa On1': 'mixed', 'Salsa On2': 'mixed', 'Salsa New York': 'mixed', 'Salsa LA': 'mixed',
};
const CUBAN_CATEGORIES = /^(Timba|Son|Afro-Cuban|Salsa Rueda|Cuban Flow)\b/;

const rows = [];
for (const f of festivals) {
  const text = [f.name, f.description].filter(Boolean).join(' · ');
  const fromText = new Set(TEXT_RULES.filter(([, re]) => re.test(text)).map(([k]) => k));
  const ext = external[f.id];
  const fromExt = new Set((ext?.styles ?? []).map((s) => EXTERNAL_STYLES[s]).filter(Boolean));
  if (ext?.category && /Rueda/.test(ext.category)) fromExt.add('rueda');

  const styles = ORDER.filter((k) => fromText.has(k) || fromExt.has(k));

  // Cuban focus: the external category first, then our text.
  let cuban = null;
  const why = [];
  if (ext?.category === 'Mixed Latin Festival') (cuban = false), why.push('their category: Mixed Latin');
  else if (ext?.category && CUBAN_CATEGORIES.test(ext.category)) (cuban = true), why.push(`their category: ${ext.category}`);
  else if (MIXED_NAME.test(f.name)) (cuban = false), why.push('other styles in the name');
  else if (fromText.has('mixed')) why.push('other styles mentioned in our description: you decide');
  else if (CUBAN_TEXT.test(text)) (cuban = true), why.push('Cuban styles named in our text');

  const flags = [];
  if (cuban === true && styles.includes('mixed')) flags.push('Cuban category but other styles listed');
  if (cuban === false && !styles.includes('mixed')) flags.push('mixed, but no other style named');
  if (cuban == null && fromText.has('mixed')) flags.push('decide: Cuban festival with other-style parties, or mixed?');
  if (!styles.length) flags.push('no style evidence');
  const agree = ext && [...fromText].filter((k) => fromExt.has(k)).length;
  const confidence = !styles.length ? 'none' : ext && fromText.size && agree ? 'high' : 'medium';

  rows.push({ id: f.id, name: f.name, listed: f.datePrecision === 'day', styles, cubanFocused: cuban, why, flags, confidence, fromText: [...fromText], fromExt: [...fromExt], ext: ext?.url ?? null, current: { styles: f.styles ?? null, cubanFocused: f.cubanFocused ?? null } });
}

mkdirSync(new URL('data/review/', root), { recursive: true });
writeFileSync(
  new URL('data/review/styles.json', root),
  JSON.stringify(Object.fromEntries(rows.filter((r) => r.styles.length || r.cubanFocused != null).map((r) => [r.id, { styles: r.styles, cubanFocused: r.cubanFocused }])), null, 2) + '\n',
);

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|');
const yesNo = (v) => (v === true ? 'yes' : v === false ? '**no (mixed)**' : '?');
const count = (fn) => rows.filter(fn).length;
const md = [
  '# Style suggestions (for review)',
  '',
  `Generated by \`node scripts/suggest-styles.mjs\` on ${new Date().toISOString().slice(0, 10)}. Nothing has been written to festivals.json.`,
  '',
  'Evidence: the festival name and our description ("ours"), and the style list and category on its cubansalsafestivals.com page ("theirs", linked).',
  '',
  `- ${rows.length} festivals: ${count((r) => r.confidence === 'high')} high confidence (both sources agree), ${count((r) => r.confidence === 'medium')} medium (one source), ${count((r) => r.confidence === 'none')} without evidence.`,
  `- Cuban-focused: ${count((r) => r.cubanFocused === true)} yes, ${count((r) => r.cubanFocused === false)} no (mixed), ${count((r) => r.cubanFocused == null)} unknown.`,
  '- To approve: edit data/review/styles.json if needed (remove a festival to leave it untagged), then run `node scripts/apply-styles.mjs`.',
  '',
  '## Decide: Cuban or mixed?',
  '',
  'Cuban styles plus bachata, kizomba or linear salsa in our description, and no category from the other site. Set `cubanFocused` to true or false in styles.json.',
  '',
  '| Festival | Styles | Ours | Theirs |',
  '|---|---|---|---|',
  ...rows.filter((r) => r.cubanFocused == null && r.fromText.includes('mixed')).map((r) => `| ${cell(r.name)} \`${r.id}\` | ${r.styles.join(', ')} | ${r.fromText.join(', ')} | ${r.ext ? `[${r.fromExt.join(', ') || '–'}](${r.ext})` : '–'} |`),
  '',
  '## Mixed festivals (Cuban-focused: no)',
  '',
  'These titles would say "Salsa Festival" instead of "Cuban Salsa Festival", and "Cuban-focused only" would hide them.',
  '',
  '| Festival | Styles | Why | Check |',
  '|---|---|---|---|',
  ...rows.filter((r) => r.cubanFocused === false).map((r) => `| ${cell(r.name)} \`${r.id}\` | ${r.styles.join(', ')} | ${cell(r.why.join('; '))}${r.ext ? ` ([theirs](${r.ext}))` : ''} | ${cell(r.flags.join('; '))} |`),
  '',
  '## All suggestions',
  '',
  '| Festival | Styles | Cuban-focused | Confidence | Ours | Theirs | Check |',
  '|---|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${cell(r.name)}${r.listed ? '' : ' (hidden)'} \`${r.id}\` | ${r.styles.join(', ') || '–'} | ${yesNo(r.cubanFocused)} | ${r.confidence} | ${r.fromText.join(', ') || '–'} | ${r.ext ? `[${r.fromExt.join(', ') || '–'}](${r.ext})` : '–'} | ${cell(r.flags.join('; '))} |`),
  '',
].join('\n');
writeFileSync(new URL('data/review/styles.md', root), md);
console.log(`${rows.length} festivals → data/review/styles.md, data/review/styles.json`);
