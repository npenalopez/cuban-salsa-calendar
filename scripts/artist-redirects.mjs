// Rewrites the artist section of public/_redirects: every alias in data/artists.json whose page
// address differs from its target's sends visitors to the target's page (en, es, fr).
//   node scripts/artist-redirects.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const reg = JSON.parse(readFileSync(new URL('data/artists.json', root), 'utf8'));
const slugify = (s) => s.normalize('NFKD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/&/g, ' and ').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const START = '# Artist spellings merged into one page (generated by scripts/artist-redirects.mjs).';
const END = '# End of artist spellings.';

const lines = [];
const seen = new Set();
for (const [variant, name] of Object.entries(reg.aliases)) {
  const from = slugify(variant);
  const to = slugify(name);
  if (!from || from === to || seen.has(from)) continue;
  seen.add(from);
  for (const pre of ['', '/es', '/fr']) lines.push(`${pre}/artists/${from}/ ${pre}/artists/${to}/ 301`);
}
const file = new URL('public/_redirects', root);
let s = readFileSync(file, 'utf8');
const block = [START, ...lines, END].join('\n');
s = s.includes(START) ? s.replace(new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`), block) : s.trimEnd() + '\n\n' + block + '\n';
writeFileSync(file, s);
console.log(`${lines.length} artist redirects in public/_redirects`);
