// Suggests the nearest useful airport (IATA) for every festival with coordinates, for review.
// Never touches festivals.json; apply the approved list with scripts/apply-airports.mjs.
//
//   node scripts/suggest-airports.mjs
//
// Rule: the nearest large airport, unless it is more than 120 km away and a medium airport
// with scheduled flights is at least 40 km closer. Writes data/review/airports.md and .json.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const { festivals } = JSON.parse(readFileSync(new URL('data/festivals.json', root), 'utf8'));
const { airports } = JSON.parse(readFileSync(new URL('scripts/data/airports.json', root), 'utf8'));

const km = (a, b, c, d) => {
  const r = (x) => (x * Math.PI) / 180;
  const h = Math.sin(r(c - a) / 2) ** 2 + Math.cos(r(a)) * Math.cos(r(c)) * Math.sin(r(d - b) / 2) ** 2;
  return 12742 * Math.asin(Math.sqrt(h));
};

const rows = [];
for (const f of festivals) {
  if (!f.coordinates) {
    rows.push({ id: f.id, name: f.name, city: f.city, suggest: null, why: 'no coordinates' });
    continue;
  }
  const [lat, lng] = f.coordinates;
  const near = airports.map(([iata, name, city, cc, alat, alng, size]) => ({ iata, name, city, cc, size, d: Math.round(km(lat, lng, alat, alng)) })).sort((a, b) => a.d - b.d);
  const large = near.find((a) => a.size === 'L');
  const medium = near.find((a) => a.size === 'M');
  let pick = large;
  let why = 'nearest large airport';
  if (!large || (large.d > 120 && medium && medium.d < large.d - 40)) {
    pick = medium;
    why = `large airport is ${large ? large.d + ' km' : 'none'}; this one is closer`;
  }
  if (pick && pick.d > 250) why += ' (far: check)';
  rows.push({ id: f.id, name: f.name, city: f.city, current: f.airport ?? null, suggest: pick?.iata ?? null, airport: pick ? `${pick.name}, ${pick.city}` : null, km: pick?.d ?? null, alt: near.slice(0, 3).filter((a) => a.iata !== pick?.iata).map((a) => `${a.iata} ${a.d} km`).join(', '), why });
}

mkdirSync(new URL('data/review/', root), { recursive: true });
writeFileSync(new URL('data/review/airports.json', root), JSON.stringify(Object.fromEntries(rows.filter((r) => r.suggest).map((r) => [r.id, r.suggest])), null, 2) + '\n');
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|');
writeFileSync(
  new URL('data/review/airports.md', root),
  [
    '# Airport suggestions (for review)',
    '',
    `Generated by \`node scripts/suggest-airports.mjs\` on ${new Date().toISOString().slice(0, 10)} from the festival coordinates and OurAirports data. Nothing has been written to festivals.json.`,
    '',
    'The airport drives the "Find flights" link on festival pages (no airport, no flights link). To approve: edit data/review/airports.json if needed (change a code, or remove a festival), then run `node scripts/apply-airports.mjs`.',
    '',
    '| Festival | City | Suggested | Airport | Distance | Other options | Why |',
    '|---|---|---|---|---|---|---|',
    ...rows.map((r) => `| ${cell(r.name)} \`${r.id}\` | ${cell(r.city)} | **${r.suggest ?? '–'}** | ${cell(r.airport)} | ${r.km ?? ''} km | ${cell(r.alt)} | ${cell(r.why)} |`),
    '',
  ].join('\n'),
);
console.log(`${rows.length} festivals → data/review/airports.md (${rows.filter((r) => r.suggest).length} with a suggestion)`);
