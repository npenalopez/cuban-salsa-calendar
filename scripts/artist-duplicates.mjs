// Lists probable duplicate artist names for review: data/review/artists.md. Changes nothing.
//
//   node scripts/artist-duplicates.mjs
//
// To merge, add the variant to `aliases` in data/artists.json ("variant": "Name to show").
// To give a one-word name a page, add it as an alias of itself or to an act.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const { festivals } = JSON.parse(readFileSync(new URL('data/festivals.json', root), 'utf8'));
const reg = JSON.parse(readFileSync(new URL('data/artists.json', root), 'utf8'));
const listed = festivals.filter((f) => f.datePrecision === 'day');

const key = (s) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9&+]+/g, ' ').trim();
const canon = new Map();
for (const n of [...Object.values(reg.aliases), ...Object.keys(reg.acts), ...Object.values(reg.acts).flat()]) canon.set(key(n), n);
for (const [v, n] of Object.entries(reg.aliases)) canon.set(key(v), n);
const show = (n) => canon.get(key(n)) ?? n.trim();
const known = new Set([...Object.keys(reg.aliases), ...Object.values(reg.aliases), ...Object.keys(reg.acts), ...Object.values(reg.acts).flat(), ...(reg.people ?? [])].map(key));

// name -> festivals
const where = new Map();
for (const f of listed) for (const a of new Set(f.artists.map(show))) where.set(a, [...(where.get(a) ?? []), f.name]);
const names = [...where.keys()];

const bare = (s) => key(s).replace(/^dj /, '');
const parts = (s) => bare(s).split(/\s*(?:&|\+| y | and | i )\s*/).map((x) => x.trim()).filter(Boolean);
const toks = (s) => bare(s).replace(/&/g, ' ').split(/\s+/).filter(Boolean);
function lev(a, b) {
  const dp = Array.from({ length: a.length + 1 }, (_, i) => [i]);
  for (let j = 1; j <= b.length; j++) dp[0][j] = j;
  for (let i = 1; i <= a.length; i++) for (let j = 1; j <= b.length; j++) dp[i][j] = Math.min(dp[i - 1][j] + 1, dp[i][j - 1] + 1, dp[i - 1][j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
  return dp[a.length][b.length];
}

const isDj = (s) => /^dj\b/i.test(s.trim());
const pairs = [];
let accentOnly = 0;
const shortHits = new Map(); // one-word name -> longer names it is a short form of
for (let i = 0; i < names.length; i++)
  for (let j = i + 1; j < names.length; j++) {
    const a = names[i], b = names[j];
    const ka = bare(a), kb = bare(b);
    let why = null;
    if (key(a) === key(b)) { accentOnly++; continue; } // already share a page
    if (ka === kb) why = 'same name, one with "DJ"';
    else if (parts(a).length === 2 && parts(b).length === 2 && [...parts(a)].sort().join('|') === [...parts(b)].sort().join('|')) why = 'same couple, other order or joiner';
    else if (parts(a).length === 2 && parts(b).length === 2 && parts(a).every((p) => parts(b).some((q) => q.split(' ')[0] === p.split(' ')[0]))) why = 'couple with the same first names';
    else {
      const ta = toks(a), tb = toks(b);
      const [s, l, sn, ln] = ta.length <= tb.length ? [ta, tb, a, b] : [tb, ta, b, a];
      const sameKind = isDj(a) === isDj(b);
      if (sameKind && !ka.includes('&') && !kb.includes('&') && s.length < l.length && s.every((t) => l.includes(t)) && s.join(' ').length >= 4) {
        if (s.length === 1) { shortHits.set(sn, [...(shortHits.get(sn) ?? []), ln]); continue; }
        why = 'one is a short form of the other';
      } else if (sameKind && toks(a).length === toks(b).length && lev(ka, kb) <= (Math.min(ka.length, kb.length) >= 15 ? 2 : 1) && Math.min(ka.length, kb.length) >= 6)
        why = 'spelling differs by one or two letters';
    }
    if (why) pairs.push({ a, b, why });
  }
// A one-word name that matches exactly one longer name is probably that person.
for (const [short, longs] of shortHits) if (longs.length === 1) pairs.push({ a: longs[0], b: short, why: 'one-word short form of exactly one name' });

const oneWord = names.filter((n) => !/\s/.test(n) && !known.has(key(n)) && (where.get(n) ?? []).length > 1);

const cell = (s) => String(s).replace(/\|/g, '\\|');
const fest = (n) => (where.get(n) ?? []).slice(0, 3).join('; ') + ((where.get(n) ?? []).length > 3 ? ` +${where.get(n).length - 3}` : '');
const md = [
  '# Artist names to review',
  '',
  `Generated by \`node scripts/artist-duplicates.mjs\` on ${new Date().toISOString().slice(0, 10)} from ${names.length} names in ${listed.length} listed festivals. Nothing has been changed.`,
  '',
  '- **Merge two names:** add the variant to `aliases` in data/artists.json, pointing to the spelling to show. Both festivals then link to one artist page.',
  `- ${accentOnly} pairs that differ only by accents or case already share one page and are not listed.`,
  '',
  `## Probable duplicates (${pairs.length})`,
  '',
  '| Name A | Name B | Why | A appears at | B appears at |',
  '|---|---|---|---|---|',
  ...pairs.map((p) => `| ${cell(p.a)} | ${cell(p.b)} | ${p.why} | ${cell(fest(p.a))} | ${cell(fest(p.b))} |`),
  '',
  `## One-word names without a page (${oneWord.length})`,
  '',
  'They appear at more than one festival and could be different people, so they have no artist page yet. If it is the same person, add the name to data/artists.json (for example `"Relampago": "Osmel Relámpago"` in `aliases`).',
  '',
  '| Name | Festivals |',
  '|---|---|',
  ...oneWord.map((n) => `| ${cell(n)} | ${cell(where.get(n).join('; '))} |`),
  '',
].join('\n');
mkdirSync(new URL('data/review/', root), { recursive: true });
writeFileSync(new URL('data/review/artists.md', root), md);
console.log(`${names.length} names: ${pairs.length} probable duplicate pairs, ${oneWord.length} one-word names without a page → data/review/artists.md`);
